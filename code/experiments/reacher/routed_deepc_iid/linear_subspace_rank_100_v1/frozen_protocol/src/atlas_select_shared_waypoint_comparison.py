def load_native_select_trajectories(reference_root: Path):
    """Load and transform the exact IID Reacher data shipped by Choose-Wisely."""
    folder = reference_root / "data/reacher/dataset_iid"
    state_paths = sorted(folder.glob("*_state.csv"), key=lambda p: int(p.name.split("_", 1)[0]))
    input_paths = sorted(folder.glob("*_input.csv"), key=lambda p: int(p.name.split("_", 1)[0]))
    if len(state_paths) != len(input_paths) or not state_paths:
        raise RuntimeError(
            f"Expected paired native Select-DPC trajectories in {folder}; "
            f"found {len(state_paths)} states and {len(input_paths)} inputs"
        )
    inputs: list[np.ndarray] = []
    outputs: list[np.ndarray] = []
    for state_path, input_path in zip(state_paths, input_paths):
        state = np.atleast_2d(np.loadtxt(state_path, delimiter=","))
        action = np.atleast_2d(np.loadtxt(input_path, delimiter=","))
        if state.shape[0] != action.shape[0]:
            raise RuntimeError(f"Length mismatch: {state_path.name} and {input_path.name}")
        state = state.copy()
        state[:, [4, 5]] += state[:, [8, 9]]
        outputs.append(state[:, [0, 1, 2, 3, 4, 5, 6, 7]])
        inputs.append(action)
    metadata = {
        "episodes": len(inputs),
        "steps_per_episode": int(inputs[0].shape[0]),
        "input_min": float(min(np.min(u) for u in inputs)),
        "input_max": float(max(np.max(u) for u in inputs)),
        "transformation": (
            "verbatim notebook fix_dataset: fingertip=(obs[4:6]+obs[8:10]), "
            "then retain raw observation indices 0:8"
        ),
    }
    return inputs, outputs, metadata


def build_select_controller(
    input_trajectories: list[np.ndarray],
    output_trajectories: list[np.ndarray],
    protocol: Protocol,
    modules,
):
    dataclasses, controllers, selectors, hankel = modules
    select_outputs = [
        y[:, SELECT_OUTPUT_INDICES] if y.shape[1] == pipe.P else y
        for y in output_trajectories
    ]
    if any(y.shape[1] != 8 for y in select_outputs):
        raise ValueError("Select-DPC trajectories must map to exactly eight outputs")
    dataset = dataclasses.TrajectoryDataSet(
        [
            dataclasses.TrajectoryData(y, u)
            for u, y in zip(input_trajectories, select_outputs)
        ],
        "shared_atlas_iid_trajectories",
    )
    dims = dataclasses.DeePCDims(T_past=2, T_fut=15, p=8, m=2)
    costs = dataclasses.DeePCCost(
        Q=np.diag([0, 0, 0, 0, 40000, 40000, 10, 10]),
        R=np.diag([10, 10]),
        slack_cost=5_000_000,
        regularizer_cost_g_1=10.0,
        regularizer_cost_g_pi=10_000,
    )
    constraints = dataclasses.DeePCConstraints(
        A_u=np.array([[1, 0], [-1, 0], [0, 1], [0, -1]]),
        b_u=np.array([0.5, 0.5, 0.5, 0.5]),
        A_y=np.array([[0, 0, 0, 0, 0, 1, 0, 0]]),
        b_y=np.array([[0.1]]),
    )
    t_hankel = (2 + 1) * (2 + 15) + 75 - 1
    args = dataclasses.DeePCControllerArgs(
        dataset, dims, t_hankel, costs, constraints, [0, 0], False
    )
    start = time.perf_counter()
    controller = controllers.SelectDeePC(
        args,
        selectors.LkSelector(),
        protocol.select_columns,
        protocol.select_refinements,
    )
    setup_time = time.perf_counter() - start
    expected_columns = len(input_trajectories) * (200 - 17 + 1)
    if controller._H_u.shape != (2 * 17, expected_columns):
        raise RuntimeError(f"Unexpected Select-DPC H_u shape {controller._H_u.shape}")
    return controller, setup_time, {
        "output_indices_from_atlas": SELECT_OUTPUT_INDICES.tolist(),
        "select_h_u_shape": list(controller._H_u.shape),
        "select_h_y_shape": list(controller._H_y.shape),
        "select_hankel_columns": int(controller._H_u.shape[1]),
        "T_past": 2,
        "T_fut": 15,
        "output_dimension": 8,
        "input_dimension": 2,
        "selected_columns": protocol.select_columns,
        "refinement_iterations": protocol.select_refinements,
        "solver": "OSQP",
        "input_bound": 0.5,
        "measurement_constraint": "fingertip y <= 0.1 over prediction horizon",
    }


def make_identical_env(protocol: Protocol):
    env_id = "Reacher-v4-atlas-select-shared"
    if env_id not in gym.envs.registry:
        gym.register(
            id=env_id,
            entry_point="gymnasium.envs.mujoco.reacher_v4:ReacherEnv",
            max_episode_steps=protocol.steps,
            reward_threshold=-3.75,
        )
    env = gym.make(env_id)
    _, _ = env.reset(seed=protocol.seed)
    unwrapped = env.unwrapped
    qpos = unwrapped.data.qpos.copy()
    qvel = unwrapped.data.qvel.copy()
    qpos[-2:] = protocol.target
    unwrapped.goal = protocol.target.copy()
    unwrapped.set_state(qpos, qvel)
    return env, unwrapped._get_obs().copy()


def build_atlas_controller(config: RoutedDeePCConfig):
    Q = np.diag(
        [
            config.q_data_goal_joint,
            config.q_data_goal_joint,
            config.q_data_goal_joint,
            config.q_data_goal_joint,
            config.q_dq,
            config.q_dq,
            config.q_xy,
            config.q_xy,
            config.q_data_goal_joint,
            config.q_data_goal_joint,
        ]
    )
    return pipe.DeePCController(
        Q,
        config.r * np.eye(pipe.M),
        np.zeros((pipe.P, pipe.P)),
        config.lam_g,
        config.lam_ini,
        config.lam_du,
        config.u_limit,
        cp.CLARABEL,
    )


def run_atlas_waypoint_generator(
    H: np.ndarray,
    atlas: dict,
    protocol: Protocol,
    save_path: Path,
) -> tuple[dict, np.ndarray, np.ndarray]:
    config = RoutedDeePCConfig(steps=protocol.steps, seed=protocol.seed)
    env, initial_obs = make_identical_env(protocol)
    initial_y = pipe.reacher_output_from_obs(initial_obs)
    goal_start = time.perf_counter()
    goal, goal_metadata = chart_compatible_goal(H, protocol.target, initial_y, config)
    goal_setup_time = time.perf_counter() - goal_start
    goal_index = int(goal_metadata["data_goal_index"])
    goal_chart = int(atlas["labels"][goal_index])
    controller = build_atlas_controller(config)

    u_history = [np.zeros(pipe.M) for _ in range(pipe.T_INI)]
    y_history = [initial_y.copy() for _ in range(pipe.T_INI)]
    latched = False
    matrix_cache: dict[tuple[int, ...], tuple[dict, np.ndarray]] = {}
    records = {
        key: []
        for key in (
            "raw_obs",
            "y",
            "u",
            "ref",
            "target_error",
            "waypoint_error",
            "status",
            "chart",
            "next_chart",
            "path_length",
            "localization_time_s",
            "routing_time_s",
            "matrix_preparation_time_s",
            "solve_time_s",
            "control_compute_time_s",
        )
    }

    obs = initial_obs.copy()
    for _ in range(protocol.steps):
        control_start = time.perf_counter()
        u_ini = np.asarray(u_history[-pipe.T_INI :]).reshape(pipe.M * pipe.T_INI, 1)
        y_ini = np.asarray(y_history[-pipe.T_INI :]).reshape(pipe.P * pipe.T_INI, 1)

        stage = time.perf_counter()
        feature = online_behavioral_feature(
            u_ini, y_ini, atlas["feature_mean"], atlas["feature_scale"]
        )
        current_chart = int(assign_charts(atlas["centers"], feature)[0])
        localization_time = time.perf_counter() - stage

        stage = time.perf_counter()
        path = shortest_chart_path(
            atlas, current_chart, goal_chart, config.edge_count_threshold
        ) or [current_chart]
        next_chart = path[1] if len(path) > 1 else current_chart
        target_distance = float(np.linalg.norm(y_history[-1][6:8] - protocol.target))
        if target_distance < config.target_switch_distance:
            latched = True
        use_target = latched if config.latch_target_reference else (
            target_distance < config.target_switch_distance
        )
        active_reference = (
            goal if use_target or current_chart == goal_chart else atlas["medoid_states"][next_chart]
        )
        reference = np.tile(active_reference.reshape(pipe.P, 1), (pipe.T_F, 1))
        routing_time = time.perf_counter() - stage

        active_charts = (current_chart,)
        stage = time.perf_counter()
        if active_charts not in matrix_cache:
            matrix_cache[active_charts] = chart_matrix(H, atlas, active_charts, config)
        matrix, _selected = matrix_cache[active_charts]
        matrix_time = time.perf_counter() - stage

        stage = time.perf_counter()
        u_solution, y_solution, _g, status, _residual = controller.solve(
            matrix, u_ini, y_ini, reference
        )
        solve_time = time.perf_counter() - stage
        action = (
            np.zeros(pipe.M)
            if u_solution is None
            else np.clip(u_solution[: pipe.M, 0], -config.u_limit, config.u_limit)
        )
        compute_time = time.perf_counter() - control_start
        obs, *_ = env.step(action)
        y_now = pipe.reacher_output_from_obs(obs)
        u_history.append(np.asarray(action).copy())
        y_history.append(y_now.copy())

        records["raw_obs"].append(obs.copy())
        records["y"].append(y_now)
        records["u"].append(action)
        records["ref"].append(active_reference.copy())
        records["target_error"].append(np.linalg.norm(y_now[6:8] - protocol.target))
        records["waypoint_error"].append(np.linalg.norm(y_now[6:8] - active_reference[6:8]))
        records["status"].append(str(status))
        records["chart"].append(current_chart)
        records["next_chart"].append(next_chart)
        records["path_length"].append(len(path))
        records["localization_time_s"].append(localization_time)
        records["routing_time_s"].append(routing_time)
        records["matrix_preparation_time_s"].append(matrix_time)
        records["solve_time_s"].append(solve_time)
        records["control_compute_time_s"].append(compute_time)
    env.close()

    arrays = {
        key: np.asarray(value, dtype=object if key == "status" else None)
        for key, value in records.items()
    }
    summary = common_tracking_summary(
        arrays["target_error"],
        arrays["waypoint_error"],
        arrays["u"],
        arrays["control_compute_time_s"],
        "atlas_deepc",
    )
    summary.update(
        controller="graph-routed rank-60 current-chart DeePC",
        qp_count=protocol.steps,
        qp_statuses=dict(Counter(arrays["status"].tolist())),
        reference_goal_setup_ms=1000 * goal_setup_time,
        unique_waypoint_xy=int(np.unique(np.round(arrays["ref"][:, 6:8], 12), axis=0).shape[0]),
        **summaries(arrays["localization_time_s"], "localization"),
        **summaries(arrays["routing_time_s"], "routing"),
        **summaries(arrays["matrix_preparation_time_s"], "matrix_preparation"),
        **summaries(arrays["solve_time_s"], "solve"),
        **goal_metadata,
    )
    np.savez(save_path, **arrays, initial_obs=initial_obs, summary=np.array(json.dumps(summary), dtype=object))
    return summary, arrays["ref"], initial_obs


def run_select_on_waypoints(
    controller,
    references_atlas: np.ndarray,
    protocol: Protocol,
    initial_obs_expected: np.ndarray,
    setup_time_s: float,
    save_path: Path,
) -> tuple[dict, np.ndarray]:
    env, initial_obs = make_identical_env(protocol)
    initial_difference = float(np.max(np.abs(initial_obs - initial_obs_expected)))
    records = {key: [] for key in ("raw_obs", "y", "u", "ref", "target_error", "waypoint_error", "status", "control_compute_time_s")}
    fallback_guard_resets = 0
    controller_exceptions: list[str] = []
    obs = initial_obs.copy()
    for step, atlas_reference in enumerate(references_atlas):
        reference = np.asarray(atlas_reference)[SELECT_OUTPUT_INDICES]
        transformed = pipe.reacher_output_from_obs(obs)[SELECT_OUTPUT_INDICES]
        # The supplied controller intends to return zero when its open-loop
        # fallback is unavailable.  Its slice-based fallback instead eventually
        # produces an empty vector after repeated OSQP ``user_limit`` statuses.
        # Reset only that exhausted fallback state; the selector, QP, solver
        # settings, and every successful action remain unchanged.
        if controller._deepc is not None:
            prior_status = str(controller._deepc._problem.status)
            if "optimal" not in prior_status:
                controller._deepc._prev_u = None
                controller._deepc._open_loop_index = 1
                fallback_guard_resets += 1
        start = time.perf_counter()
        try:
            action = controller.compute_action(transformed, reference)
        except (ValueError, IndexError) as exc:
            controller_exceptions.append(f"{type(exc).__name__}: {exc}")
            action = np.zeros(2)
            if controller._deepc is not None:
                controller._deepc._prev_u = None
                controller._deepc._open_loop_index = 1
        compute_time = time.perf_counter() - start
        obs, *_ = env.step(action)
        y_now_atlas = pipe.reacher_output_from_obs(obs)
        y_now = y_now_atlas[SELECT_OUTPUT_INDICES]
        records["raw_obs"].append(obs.copy())
        records["y"].append(y_now)
        records["u"].append(action)
        records["ref"].append(reference)
        records["target_error"].append(np.linalg.norm(y_now[4:6] - protocol.target))
        records["waypoint_error"].append(np.linalg.norm(y_now[4:6] - reference[4:6]))
        records["status"].append(str(controller._deepc._problem.status))
        records["control_compute_time_s"].append(compute_time)
        if (step + 1) % 10 == 0:
            print(
                f"Select-DPC completed {step + 1}/{len(references_atlas)} steps; "
                f"latest status={records['status'][-1]}",
                flush=True,
            )
    env.close()
    arrays = {
        key: np.asarray(value, dtype=object if key == "status" else None)
        for key, value in records.items()
    }
    native_selection = controller._solve_time_avg["selection"]
    native_solve = controller._solve_time_avg["solve"]
    summary = common_tracking_summary(
        arrays["target_error"],
        arrays["waypoint_error"],
        arrays["u"],
        arrays["control_compute_time_s"],
        "select_dpc",
    )
    summary.update(
        controller="original Select-DPC formulation with shared-data trajectories",
        qp_count=protocol.steps * protocol.select_refinements,
        final_iteration_statuses=dict(Counter(arrays["status"].tolist())),
        controller_setup_ms=1000 * setup_time_s,
        native_mean_selection_per_refinement_ms=1000 * float(native_selection._avg),
        native_mean_solve_per_refinement_ms=1000 * float(native_solve._avg),
        estimated_mean_selection_per_step_ms=(
            1000 * protocol.select_refinements * float(native_selection._avg)
        ),
        estimated_mean_solve_per_step_ms=(
            1000 * protocol.select_refinements * float(native_solve._avg)
        ),
        initial_observation_max_abs_difference=initial_difference,
        fallback_guard_resets=fallback_guard_resets,
        controller_exception_count=len(controller_exceptions),
        controller_exceptions=dict(Counter(controller_exceptions)),
        fallback_guard=(
            "When the original open-loop fallback buffer was exhausted after a "
            "non-optimal solve, reset it to the controller's documented zero-input fallback."
        ),
    )
    np.savez(save_path, **arrays, initial_obs=initial_obs, summary=np.array(json.dumps(summary), dtype=object))
    return summary, initial_obs


def make_figure(output_dir: Path, atlas_data: dict, select_data: dict) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(12.5, 3.4))
    target = np.asarray(atlas_data["target"])
    for label, data, color in (
        ("Atlas-DeePC", atlas_data, "tab:blue"),
        ("Select-DPC", select_data, "tab:orange"),
    ):
        axes[0].plot(1000 * data["target_error"], label=label, color=color)
        axes[1].plot(1000 * data["waypoint_error"], label=label, color=color)
        axes[2].plot(1000 * data["control_compute_time_s"], label=label, color=color, alpha=0.85)
    axes[0].set(title="Final-target tracking", xlabel="Control step", ylabel="Error [mm]")
    axes[1].set(title="Shared-waypoint tracking", xlabel="Control step", ylabel="Error [mm]")
    axes[2].set(title="End-to-end online compute", xlabel="Control step", ylabel="Time [ms]", yscale="log")
    for axis in axes:
        axis.grid(alpha=0.25)
    axes[0].legend()
    fig.suptitle(f"Shared offline trajectories, graph waypoints, target=({target[0]:.3f}, {target[1]:.3f})")
    fig.tight_layout()
    fig.savefig(output_dir / "comparison.png", dpi=180, bbox_inches="tight")
    fig.savefig(output_dir / "comparison.pdf", bbox_inches="tight")
    plt.close(fig)


def main(args: argparse.Namespace) -> None:
    protocol = Protocol(
        seed=args.seed,
        steps=args.steps,
        target_x=args.target_x,
        target_y=args.target_y,
        select_columns=args.select_columns,
        select_refinements=args.select_refinements,
    )
    args.output_dir.mkdir(parents=True, exist_ok=True)
    H = np.load(args.data_path)
    atlas = load_atlas(args.atlas_path)
    inputs, outputs, reconstruction = reconstruct_trajectories(H)

    with tempfile.TemporaryDirectory(prefix="choose_wisely_reference_") as temp:
        reference_root = extract_reference_package(args.select_code_zip, Path(temp))
        modules = import_reference_select_dpc(reference_root)
        select_controller, select_setup, select_metadata = build_select_controller(
            inputs, outputs, protocol, modules
        )

        atlas_path = args.output_dir / "atlas_control_results.npz"
        select_path = args.output_dir / "select_control_results.npz"
        atlas_summary, references, atlas_initial = run_atlas_waypoint_generator(
            H, atlas, protocol, atlas_path
        )
        select_summary, select_initial = run_select_on_waypoints(
            select_controller,
            references,
            protocol,
            atlas_initial,
            select_setup,
            select_path,
        )

    reference_mapping_error = float(
        np.max(
            np.abs(
                references[:, [0, 1, 2, 3, 6, 7, 4, 5]]
                - references[:, SELECT_OUTPUT_INDICES]
            )
        )
    )
    latency_ratio = (
        select_summary["median_control_compute_ms"]
        / atlas_summary["median_control_compute_ms"]
    )
    payload = {
        "benchmark": "Atlas-DeePC versus original-form Select-DPC with shared trajectories and graph waypoints",
        "protocol": {
            **asdict(protocol),
            "environment": "Reacher-v4-custom (no rendering)",
            "initial_history": "each controller's native repeated-state/zero-input initialization",
            "reference_protocol": "Atlas generates the causal waypoint schedule; the identical physical reference is replayed to Select-DPC",
            "timing_boundary": "complete controller work between observation/reference availability and returned action; MuJoCo step excluded",
        },
        "shared_data": {
            "path": str(args.data_path.resolve()),
            "sha256": sha256_file(args.data_path),
            **reconstruction,
            **select_metadata,
        },
        "source_provenance": {
            "select_dpc_archive": str(args.select_code_zip.resolve()),
            "select_dpc_archive_sha256": sha256_file(args.select_code_zip),
            "source_use": (
                "imported unchanged; in-memory shared-data conversion, observational "
                "timing, and the disclosed exhausted-fallback safety guard"
            ),
            "atlas_path": str(args.atlas_path.resolve()),
            "atlas_sha256": sha256_file(args.atlas_path),
        },
        "fairness_checks": {
            "initial_observation_max_abs_difference": float(np.max(np.abs(atlas_initial - select_initial))),
            "reference_mapping_max_abs_error": reference_mapping_error,
            "reference_steps": int(references.shape[0]),
            "same_seed": True,
            "same_target": True,
            "same_underlying_offline_trajectories": True,
        },
        "results": [atlas_summary, select_summary],
        "comparison": {
            "median_latency_ratio_select_over_atlas": float(latency_ratio),
            "qp_count_ratio_select_over_atlas": float(select_summary["qp_count"] / atlas_summary["qp_count"]),
            "interpretation": "Timing is primary; tracking is secondary because native costs, horizons, constraints, representations, and solvers intentionally differ.",
        },
    }
    (args.output_dir / "summary.json").write_text(json.dumps(payload, indent=2))

    atlas_npz = np.load(atlas_path, allow_pickle=True)
    select_npz = np.load(select_path, allow_pickle=True)
    make_figure(
        args.output_dir,
        {
            "target": protocol.target,
            "target_error": atlas_npz["target_error"],
            "waypoint_error": atlas_npz["waypoint_error"],
            "control_compute_time_s": atlas_npz["control_compute_time_s"],
        },
        {
            "target_error": select_npz["target_error"],
            "waypoint_error": select_npz["waypoint_error"],
            "control_compute_time_s": select_npz["control_compute_time_s"],
        },
    )
    print(json.dumps(payload["comparison"], indent=2), flush=True)
    for result in payload["results"]:
        print(
            f"{result['method']}: median={result['median_control_compute_ms']:.2f} ms, "
            f"p95={result['p95_control_compute_ms']:.2f} ms, "
            f"target_final={1000 * result['final_target_error_m']:.2f} mm, "
            f"waypoint_rmse={1000 * result['waypoint_rmse_m']:.2f} mm",
            flush=True,
        )


