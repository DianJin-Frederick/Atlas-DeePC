@dataclass
class Protocol:
    seed: int = 0
    steps: int = 100
    target_x: float = 0.043
    target_y: float = 0.092
    select_columns: int = 200
    select_refinements: int = 5

    @property
    def target(self) -> np.ndarray:
        return np.array([self.target_x, self.target_y], dtype=float)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def summaries(values: np.ndarray, name: str) -> dict[str, float]:
    values = 1000.0 * np.asarray(values, dtype=float)
    steady = values[min(5, values.size) :]
    if steady.size == 0:
        steady = values
    return {
        f"mean_{name}_ms": float(np.mean(values)),
        f"median_{name}_ms": float(np.median(values)),
        f"p95_{name}_ms": float(np.percentile(values, 95)),
        f"max_{name}_ms": float(np.max(values)),
        f"steady_median_{name}_ms": float(np.median(steady)),
        f"steady_p95_{name}_ms": float(np.percentile(steady, 95)),
    }


def common_tracking_summary(
    target_error: np.ndarray,
    waypoint_error: np.ndarray,
    actions: np.ndarray,
    compute_time_s: np.ndarray,
    name: str,
) -> dict:
    tail = target_error[-min(30, target_error.size) :]
    reached = np.where(target_error < 0.005)[0]
    return {
        "method": name,
        "steps": int(target_error.size),
        "target_rmse_m": float(np.sqrt(np.mean(target_error**2))),
        "waypoint_rmse_m": float(np.sqrt(np.mean(waypoint_error**2))),
        "minimum_target_error_m": float(np.min(target_error)),
        "final_target_error_m": float(target_error[-1]),
        "mean_final_30_target_error_m": float(np.mean(tail)),
        "max_final_30_target_error_m": float(np.max(tail)),
        "reached_5mm_step": int(reached[0]) if reached.size else None,
        "success_final_30": bool(np.mean(tail) < 0.01 and np.max(tail) < 0.02),
        "action_rms": float(np.sqrt(np.mean(actions**2))),
        **summaries(compute_time_s, "control_compute"),
    }


def reconstruct_trajectories(H: np.ndarray) -> tuple[list[np.ndarray], list[np.ndarray], dict]:
    """Invert the ordered overlapping Atlas windows into 200 length-200 traces."""
    windows_per_episode = 200 - pipe.L + 1
    if H.shape[1] % windows_per_episode:
        raise ValueError(
            f"{H.shape[1]} columns are not divisible by {windows_per_episode} windows/episode"
        )
    U = H[: pipe.M * pipe.L].reshape(pipe.L, pipe.M, H.shape[1])
    Y = H[pipe.M * pipe.L :].reshape(pipe.L, pipe.P, H.shape[1])
    input_trajectories: list[np.ndarray] = []
    output_trajectories: list[np.ndarray] = []
    maximum_overlap_error = 0.0
    for start in range(0, H.shape[1], windows_per_episode):
        stop = start + windows_per_episode
        u_windows = U[:, :, start:stop]
        y_windows = Y[:, :, start:stop]
        maximum_overlap_error = max(
            maximum_overlap_error,
            float(np.max(np.abs(u_windows[1:, :, :-1] - u_windows[:-1, :, 1:]))),
            float(np.max(np.abs(y_windows[1:, :, :-1] - y_windows[:-1, :, 1:]))),
        )
        input_trajectories.append(
            np.vstack([u_windows[:, :, 0], u_windows[-1, :, 1:].T])
        )
        output_trajectories.append(
            np.vstack([y_windows[:, :, 0], y_windows[-1, :, 1:].T])
        )
    metadata = {
        "episodes": len(input_trajectories),
        "steps_per_episode": int(input_trajectories[0].shape[0]),
        "atlas_hankel_columns": int(H.shape[1]),
        "maximum_overlap_reconstruction_error": maximum_overlap_error,
    }
    return input_trajectories, output_trajectories, metadata


def extract_reference_package(archive_path: Path, destination: Path) -> Path:
    with zipfile.ZipFile(archive_path) as archive:
        members = [
            name
            for name in archive.namelist()
            if name.startswith(f"{ARCHIVE_ROOT}/select_deepc/")
            or name.startswith(f"{ARCHIVE_ROOT}/data/reacher/dataset_iid/")
        ]
        archive.extractall(destination, members=members)
    return destination / ARCHIVE_ROOT


